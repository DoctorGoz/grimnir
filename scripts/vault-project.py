#!/usr/bin/env python3
"""vault-project.py — project engagement data into a read-only Obsidian vault.

WHAT / WHY
    Obsidian is a browse/query lens, never the source of truth. The engagement stores
    (state.json, findings/*.json, intel.jsonl) stay authoritative; this renders a READ-ONLY
    markdown projection of them into an operator-local vault so engagements are navigable in
    Obsidian's graph/search. It NEVER writes back to an engagement dir and only ever writes
    under the vault.

    Memory (~/.claude/.../memory) needs no projection — it is already a wikilink graph; point
    Obsidian at it directly. This script covers engagement/program data only.

SOURCE OF TRUTH / SAFETY
    - Reads engagement dirs under $GRIMNIR_WORKSPACE (default ~/workspace); an engagement is any
      subdir containing state.json.
    - Writes only under $GRIMNIR_VAULT (default ~/grimnir-vault). REFUSES to run if the vault
      resolves inside the git repo, equals/contains the workspace, or is a parent of it — a
      projection must never clobber source or tracked files.
    - Pages carry a "generated — do not edit" banner; hand edits are overwritten next run.

INCREMENTAL
    Regenerates a program's page only when a source file is newer than the page (or --all). The
    index is always rebuilt (cheap). Suits a nightly cron over the changed/active programs.

USAGE
    vault-project.py                 # incremental projection to the default vault
    vault-project.py --all           # rebuild every page
    vault-project.py --program acme  # just one
    vault-project.py --dry-run       # show what would change, write nothing
    vault-project.py --selftest      # pure-function checks, no I/O
"""
from __future__ import annotations
import argparse
import json
import os
import sys
from pathlib import Path

SEV_ORDER = ["critical", "high", "medium", "low", "info"]
GEN_BANNER = ("> [!note] Generated by grimnir `vault-project.py` — read-only projection, edits are "
              "overwritten. Source of truth is the engagement dir.")


# ── pure helpers (unit-tested; no I/O) ────────────────────────────────────────────────────────
def severity_rank(sev: str) -> int:
    s = (sev or "").lower()
    return SEV_ORDER.index(s) if s in SEV_ORDER else len(SEV_ORDER)


def sev_counts(findings: list) -> dict:
    c = {s: 0 for s in SEV_ORDER}
    for f in findings:
        s = (f.get("severity") or "").lower()
        if s in c:
            c[s] += 1
    return c


def _yaml_str(v) -> str:
    """Quote a scalar for YAML frontmatter (safe for ':', '#', etc.)."""
    return json.dumps("" if v is None else str(v), ensure_ascii=False)


def _cell(v) -> str:
    return str("" if v is None else v).replace("|", "\\|").replace("\n", " ").strip()


def _norm_finding(f: dict) -> dict:
    val = f.get("validation") or {}
    sub = f.get("submission") or {}
    return {
        "id": f.get("id") or "?",
        "severity": (f.get("severity") or "?").lower(),
        "title": f.get("title") or "",
        "status": f.get("status") or "",
        "vstate": val.get("state") or "theoretical",
        "victim": bool(val.get("victim_data")),
        "disposition": f.get("disposition") or "",
        "agent": f.get("agent") or "",
        "outcome": sub.get("state") or "",
        "report_id": sub.get("report_id") or "",
        "bounty": sub.get("bounty"),
    }


def _target_str(tgt) -> str:
    """state.json 'target' is a dict ({primary/endpoint}) on most engagements but a bare string on
    some older ones — accept both (and neither)."""
    if isinstance(tgt, dict):
        return tgt.get("primary") or tgt.get("endpoint") or ""
    return tgt if isinstance(tgt, str) else ""


def normalize_engagement(state: dict, findings: list, intel: list) -> dict:
    """Pure: shape the raw sources into the dict the renderers consume. Defensive against
    string-typed target, non-dict agents, and non-dict intel/finding rows seen in real data.
    Findings sort by severity (critical first) then newest-first within a severity."""
    findings = [f for f in (findings or []) if isinstance(f, dict)]
    intel = [i for i in (intel or []) if isinstance(i, dict)]
    fs = sorted(findings, key=lambda f: f.get("created_at") or "", reverse=True)
    fs = sorted(fs, key=lambda f: severity_rank(f.get("severity")))
    return {
        "program": state.get("project_name") or "unknown",
        "slug": state.get("project_name") or "unknown",  # caller overrides with the dir name
        "engagement_id": state.get("engagement_id") or "",
        "status": state.get("status") or "unknown",
        "target": _target_str(state.get("target")),
        "created_at": state.get("created_at") or "",
        "updated_at": state.get("updated_at") or "",
        "agents": state.get("agents") if isinstance(state.get("agents"), dict) else {},
        "findings": [_norm_finding(f) for f in fs],
        "counts": sev_counts(findings),
        "intel_recent": intel[-10:][::-1],
        "intel_total": len(intel),
    }


def _counts_str(c: dict) -> str:
    return f"C{c['critical']} H{c['high']} M{c['medium']} L{c['low']} I{c['info']}"


def render_engagement_page(eng: dict) -> str:
    c = eng["counts"]
    slug = eng.get("slug") or eng["program"]
    fm = ["---",
          f"program: {_yaml_str(eng['program'])}",
          f"engagement_id: {_yaml_str(eng['engagement_id'])}",
          f"status: {_yaml_str(eng['status'])}",
          f"target: {_yaml_str(eng['target'])}",
          f"updated: {_yaml_str(eng['updated_at'])}",
          f"findings_total: {len(eng['findings'])}",
          f"findings_by_severity: {_yaml_str(_counts_str(c))}"]
    if eng["program"] != slug:
        fm += ["aliases:", f"  - {_yaml_str(eng['program'])}"]
    fm += ["tags:", "  - grimnir/engagement", f"  - grimnir/status/{eng['status']}", "---", ""]

    body = [f"# {eng['program']}", "", GEN_BANNER, "",
            f"- **Status:** {eng['status']}",
            f"- **Target:** {eng['target'] or '—'}",
            f"- **Engagement:** {eng['engagement_id'] or '—'}",
            f"- **Findings:** {len(eng['findings'])}  ({_counts_str(c)})",
            f"- **Updated:** {eng['updated_at'] or '—'}",
            "", "## Findings", ""]
    if eng["findings"]:
        body += ["| id | sev | valid | victim | outcome | title |",
                 "|----|-----|-------|--------|---------|-------|"]
        for f in eng["findings"]:
            outcome = f["outcome"] + (f" ({f['report_id']})" if f["report_id"] else "")
            if f["disposition"]:
                outcome = (outcome + " / " + f["disposition"]).strip(" /")
            body.append(f"| {_cell(f['id'])} | {_cell(f['severity'])} | {_cell(f['vstate'])} | "
                        f"{'yes' if f['victim'] else ''} | {_cell(outcome) or '—'} | {_cell(f['title'])} |")
    else:
        body.append("_No findings recorded._")

    body += ["", "## Agent progress", ""]
    if eng["agents"]:
        for name, a in eng["agents"].items():
            body.append(f"### {name}")
            if isinstance(a, dict):
                body.append(f"- phase **{a.get('phase', '?')}** · status **{a.get('status', '?')}** · "
                            f"progress {a.get('progress', '?')}")
                if a.get("next_action"):
                    body.append(f"- next: {_cell(a['next_action'])}")
            else:
                body.append(f"- {_cell(a)}")
            body.append("")
    else:
        body.append("_No agent state._")
        body.append("")

    if eng["intel_recent"]:
        body += [f"## Recent intel (last {len(eng['intel_recent'])} of {eng['intel_total']})", ""]
        for it in eng["intel_recent"]:
            tg = ",".join(it.get("tags") or [])
            conf = it.get("confidence")
            body.append(f"- **{_cell(it.get('discovery_type') or '?')}**"
                        f"{(' [' + tg + ']') if tg else ''}"
                        f"{(' · ' + str(conf)) if conf not in (None, '') else ''}")
        body.append("")
    return "\n".join(fm + body).rstrip() + "\n"


def render_index(engs: list) -> str:
    engs2 = sorted(engs, key=lambda e: e.get("updated_at") or "", reverse=True)
    tot = {s: sum(e["counts"][s] for e in engs) for s in SEV_ORDER}
    out = ["---", "tags:", "  - grimnir/index", "---", "",
           "# Engagements", "", GEN_BANNER, "",
           f"{len(engs)} engagements · findings {_counts_str(tot)}", "",
           "| program | status | findings | updated |",
           "|---------|--------|----------|---------|"]
    for e in engs2:
        c = e["counts"]
        slug = e.get("slug") or e["program"]
        link = f"[[{slug}|{e['program']}]]" if e["program"] != slug else f"[[{slug}]]"
        out.append(f"| {link} | {_cell(e['status'])} | C{c['critical']} H{c['high']} "
                   f"M{c['medium']} L{c['low']} | {_cell((e['updated_at'] or '')[:10])} |")
    return "\n".join(out).rstrip() + "\n"


def is_safe_vault(vault: str, workspace: str, repo_dir: str | None) -> tuple[bool, str]:
    """A projection must never clobber source or tracked files."""
    v = Path(vault).expanduser().resolve()
    ws = Path(workspace).expanduser().resolve()
    if str(v) in ("", "/"):
        return False, "vault path is empty or root"
    if v == ws or ws in v.parents:
        return False, "vault is inside or equal to the workspace"
    if v in ws.parents:
        return False, "vault is a parent of the workspace"
    if repo_dir:
        repo = Path(repo_dir).expanduser().resolve()
        if v == repo or repo in v.parents or v in repo.parents:
            return False, "vault overlaps the git repo"
    return True, "ok"


# ── I/O ───────────────────────────────────────────────────────────────────────────────────────
def _read_json(p: Path):
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def load_engagement_sources(d: Path):
    state = _read_json(d / "state.json") or {}
    # Findings live either in the merged top-level findings/ or in a per-agent <agent>/findings/.
    # Read both, dedup by id, and let the merged top-level copy win on a collision.
    by_id, order = {}, []
    agent_dirs = [d / a / "findings" for a in ("huginn", "specter", "artemis", "hunter", "nimbus", "nomad")]
    for fdir in agent_dirs + [d / "findings"]:
        if fdir.is_dir():
            for fp in sorted(fdir.glob("*.json")):
                fj = _read_json(fp)
                if isinstance(fj, dict) and fj.get("id"):
                    if fj["id"] not in by_id:
                        order.append(fj["id"])
                    by_id[fj["id"]] = fj
    findings = [by_id[i] for i in order]
    intel = []
    ip = d / "intel.jsonl"
    if ip.is_file():
        for line in ip.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.strip()
            if line:
                try:
                    obj = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if isinstance(obj, dict):
                    intel.append(obj)
    return state, findings, intel


def discover_engagements(workspace: str) -> list:
    ws = Path(workspace).expanduser()
    if not ws.is_dir():
        return []
    return [d for d in sorted(ws.iterdir()) if d.is_dir() and (d / "state.json").is_file()]


def source_mtime(d: Path) -> float:
    mt = 0.0
    for p in (d / "state.json", d / "intel.jsonl"):
        if p.exists():
            mt = max(mt, p.stat().st_mtime)
    fdir = d / "findings"
    if fdir.is_dir():
        for fp in fdir.glob("*.json"):
            mt = max(mt, fp.stat().st_mtime)
    return mt


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Project engagement data into a read-only Obsidian vault.")
    ap.add_argument("--workspace", default=os.environ.get("GRIMNIR_WORKSPACE") or os.path.expanduser("~/workspace"))
    ap.add_argument("--vault", default=os.environ.get("GRIMNIR_VAULT") or os.path.expanduser("~/grimnir-vault"))
    ap.add_argument("--program", help="project just one engagement (dir name)")
    ap.add_argument("--all", action="store_true", help="rebuild every page, ignore mtimes")
    ap.add_argument("--dry-run", action="store_true", help="show what would change, write nothing")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args(argv)
    if args.selftest:
        return _selftest()

    repo_dir = os.environ.get("GRIMNIR_REPO_DIR") or os.path.expanduser("~/workspace/grimnir")
    ok, why = is_safe_vault(args.vault, args.workspace, repo_dir)
    if not ok:
        print(f"[vault-project] refusing: {why} (vault={args.vault})", file=sys.stderr)
        return 2

    dirs = discover_engagements(args.workspace)
    if args.program:
        dirs = [d for d in dirs if d.name == args.program]
        if not dirs:
            print(f"[vault-project] no engagement dir named {args.program}", file=sys.stderr)
            return 1

    engpages = Path(args.vault).expanduser() / "engagements"
    if not args.dry_run:
        engpages.mkdir(parents=True, exist_ok=True)

    written = skipped = 0
    all_norm = []
    for d in dirs:
        page = engpages / f"{d.name}.md"
        need = args.all or not page.exists() or source_mtime(d) > page.stat().st_mtime
        state, findings, intel = load_engagement_sources(d)
        norm = normalize_engagement(state, findings, intel)
        norm["slug"] = d.name
        norm["program"] = state.get("project_name") or d.name
        all_norm.append(norm)
        if not need:
            skipped += 1
            continue
        content = render_engagement_page(norm)
        if args.dry_run:
            print(f"[dry-run] would write {page} ({len(content)} bytes)")
        else:
            page.write_text(content, encoding="utf-8")
        written += 1

    idx = engpages / "_Engagements.md"
    if args.dry_run:
        print(f"[dry-run] would write {idx} ({len(all_norm)} engagements)")
    else:
        idx.write_text(render_index(all_norm), encoding="utf-8")
    print(f"[vault-project] {written} written, {skipped} unchanged, {len(all_norm)} total -> {args.vault}")
    return 0


def _selftest() -> int:
    assert severity_rank("critical") < severity_rank("high") < severity_rank("info")
    assert severity_rank("bogus") == len(SEV_ORDER)
    assert sev_counts([{"severity": "low"}, {"severity": "critical"}, {"severity": "x"}]) \
        == {"critical": 1, "high": 0, "medium": 0, "low": 1, "info": 0}

    state = {"project_name": "acme", "status": "in_progress", "engagement_id": "ENG-1",
             "target": {"primary": "https://api.acme.test"}, "updated_at": "2026-09-25T00:00:00Z",
             "agents": {"specter": {"phase": "test", "status": "in_progress", "progress": 0.9,
                                    "next_action": "probing the widget"}}}
    findings = [
        {"id": "SPE-002", "severity": "high", "title": "BOLA on /x", "status": "confirmed",
         "validation": {"state": "confirmed", "victim_data": True},
         "submission": {"state": "open", "report_id": "1234"}, "agent": "specter"},
        {"id": "SPE-005", "severity": "low", "title": "Header | with pipe",
         "validation": {"state": "theoretical"}},
    ]
    norm = normalize_engagement(state, findings, [{"discovery_type": "endpoint", "confidence": "high",
                                                   "tags": ["api"]}])
    norm["slug"] = "acme"
    assert norm["findings"][0]["id"] == "SPE-002"  # high sorts before low
    page = render_engagement_page(norm)
    assert "# acme" in page and "SPE-002" in page and "https://api.acme.test" in page
    assert "\\|" in page                       # pipe in a title is escaped
    assert "| yes |" in page                   # victim-data marker rendered
    assert "probing the widget" in page
    idx = render_index([norm])
    assert "[[acme]]" in idx and "# Engagements" in idx

    ok, _ = is_safe_vault("/home/x/vault", "/home/x/workspace", "/home/x/workspace/grimnir")
    assert ok
    bad, _ = is_safe_vault("/home/x/workspace", "/home/x/workspace", None)
    assert not bad
    bad2, _ = is_safe_vault("/home/x/workspace/grimnir/v", "/home/x/workspace", "/home/x/workspace/grimnir")
    assert not bad2
    bad3, _ = is_safe_vault("/home/x/workspace/sub", "/home/x/workspace", None)
    assert not bad3  # inside the workspace

    # defensive against real-data shapes: string target, non-dict agents, non-dict intel rows
    assert _target_str("https://x") == "https://x" and _target_str({"primary": "p"}) == "p"
    assert _target_str(None) == ""
    n2 = normalize_engagement({"project_name": "s", "target": "https://s.test", "agents": []},
                              [], ["bad-row", {"discovery_type": "e"}])
    assert n2["target"] == "https://s.test" and n2["agents"] == {} and len(n2["intel_recent"]) == 1
    n3 = normalize_engagement({"project_name": "s",
                               "agents": {"specter": "done-note", "huginn": {"phase": "recon"}}}, [], [])
    n3["slug"] = "s"
    p3 = render_engagement_page(n3)  # a string-valued agent must not crash the render
    assert "done-note" in p3 and "recon" in p3
    print("vault-project selftest OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
