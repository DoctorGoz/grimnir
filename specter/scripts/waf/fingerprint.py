def _norm_headers(headers) -> Dict[str, str]:
    if headers is None:
        return {}
    if hasattr(headers, "items"):
        return {str(k).lower(): str(v) for k, v in headers.items()}
    return {str(k).lower(): str(v) for k, v in headers}


def _score(sig: Signature, headers: Dict[str, str], cookies: str,
           body: str, status: Optional[int]) -> Tuple[float, List[str]]:
    conf = 0.0
    matched: List[str] = []
    for hn, pat in sig.headers.items():
        v = headers.get(hn.lower())
        if v is not None and re.search(pat, v, re.IGNORECASE):
            conf += _W["header"]; matched.append(f"header:{hn}")
    for hn in sig.header_names:
        if hn.lower() in headers:
            conf += _W["header_name"]; matched.append(f"header:{hn}")
    server = headers.get("server", "")
    for pat in sig.server:
        if re.search(pat, server, re.IGNORECASE):
            conf += _W["server"]; matched.append(f"server:{pat}")
    cookie_blob = cookies or headers.get("set-cookie", "")
    for pat in sig.cookies:
        if re.search(pat, cookie_blob, re.IGNORECASE):
            conf += _W["cookie"]; matched.append(f"cookie:{pat}")
    for pat in sig.body:
        if body and re.search(pat, body, re.IGNORECASE):
            conf += _W["body"]; matched.append(f"body:{pat[:24]}")
    if status is not None and status in sig.statuses and matched:
        # status alone is meaningless; only counts when another signal already hit
        conf += _W["status"]; matched.append(f"status:{status}")
    return conf, matched


def passive_fingerprint(headers=None, cookies: str = "", body: str = "",
                status: Optional[int] = None,
                min_confidence: float = 0.4) -> Dict:
    """Passive fingerprint. Returns {waf, confidence, candidates, signals}.

    `waf` is the top product at or above `min_confidence`, else "none". Generic only
    wins if no branded product scored.
    """
    hdr = _norm_headers(headers)
    ranked: List[Tuple[str, float, List[str]]] = []
    for sig in WAF_SIGNATURES:
        c, matched = _score(sig, hdr, cookies, body, status)
        if c > 0:
            ranked.append((sig.waf, min(round(c, 3), 1.0), matched))
    # prefer branded products over "generic" at equal-ish confidence
    ranked.sort(key=lambda r: (r[1], r[0] != "generic"), reverse=True)

    winner = "none"
    conf = 0.0
    signals: List[str] = []
    branded = [r for r in ranked if r[0] != "generic"]
    pick = branded[0] if branded and branded[0][1] >= min_confidence else (ranked[0] if ranked else None)
    if pick and pick[1] >= min_confidence:
        winner, conf, signals = pick

    return {
        "waf": winner,
        "confidence": conf,
        "candidates": [{"waf": w, "confidence": c, "signals": m} for w, c, m in ranked[:5]],
        "signals": signals,
    }


def detect(url: str, timeout: float = 12.0, active: bool = False,
           user_agent: str = "Mozilla/5.0 (compatible; grimnir-waf/1.0)") -> Dict:
    """Fetch `url` and fingerprint. If active, also send one benign noisy probe and
    merge whichever response scored higher. Network errors degrade gracefully."""
    result = _fetch_and_fp(url, timeout, user_agent)
    if active:
        sep = "&" if "?" in url else "?"
        probe_url = f"{url}{sep}grimnirwaf=%3Cscript%3E1%3C%2Fscript%3E%20or%201%3D1--"
        probed = _fetch_and_fp(probe_url, timeout, user_agent)
        if probed.get("confidence", 0) > result.get("confidence", 0):
            probed["active_probe"] = True
            return probed
    return result


_EGRESS = None


def _egress_mod():
    """The egress module (scripts/egress.py), imported lazily so the offline passive-fingerprint
    path and its tests never depend on it. Active probes are target traffic and ride its proxy."""
    global _EGRESS
    if _EGRESS is None:
        import os
        import sys
        repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
        sp = os.path.join(repo, "scripts")
        if sp not in sys.path:
            sys.path.insert(0, sp)
        import egress
        _EGRESS = egress
    return _EGRESS


def _egress_opener():
    """A urllib opener that rides the program's egress proxy when one is configured (fail closed:
    an unusable proxy raises EgressError, so the probe refuses rather than going direct)."""
    eg = _egress_mod()
    return eg.opener(proxy=eg.proxy())


def _fetch_and_fp(url: str, timeout: float, ua: str) -> Dict:
    req = _request.Request(url, headers={"User-Agent": ua, "Accept": "*/*"})
    try:
        with _egress_opener().open(req, timeout=timeout) as resp:
            raw = resp.read(65536)
            body = raw.decode("utf-8", "replace")
            fp = passive_fingerprint(resp.headers, body=body, status=resp.status)
            fp["fetch"] = {"status": resp.status, "url": url}
            return fp
    except HTTPError as e:  # a WAF block is usually an HTTPError (403/406/503)
        body = ""
        try:
            body = e.read(65536).decode("utf-8", "replace")
        except Exception:
            pass
        fp = passive_fingerprint(e.headers, body=body, status=e.code)
        fp["fetch"] = {"status": e.code, "url": url}
        return fp
    except (URLError, OSError, ValueError) as e:
        return {"waf": "none", "confidence": 0.0, "candidates": [],
                "signals": [], "fetch": {"error": str(e), "url": url}}
