"""
WAF product fingerprinter.

Passive: given a response's headers/cookies/body/status, score which WAF product is in
front of the origin. Optional active mode sends ONE benign noisy probe to elicit a block
page and fingerprints that. Confidence is the summed signal weight, capped at 1.0.

Returns (waf_id, confidence, matched_signals). waf_id is one of WAF_IDS, or "none".
The id feeds encodings.encode_payload() so variant selection leans on techniques that
tend to beat that product.

Stdlib only. Active mode uses urllib; keep probes benign and single -- this is
fingerprinting, not attack traffic.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple
from urllib import request as _request
from urllib.error import HTTPError, URLError

WAF_IDS = [
    "cloudflare", "aws_waf", "akamai", "modsecurity", "imperva",
    "f5_bigip", "sucuri", "fortiweb", "barracuda", "naxsi", "generic",
]


@dataclass
class Signature:
    waf: str
    headers: Dict[str, str] = field(default_factory=dict)   # header-name -> regex on value
    header_names: List[str] = field(default_factory=list)   # presence of a header name
    cookies: List[str] = field(default_factory=list)        # cookie-name regexes
    body: List[str] = field(default_factory=list)           # block-page body regexes
    server: List[str] = field(default_factory=list)         # Server-header regexes
    statuses: List[int] = field(default_factory=list)       # block status codes (weak signal)


# weights per signal kind
_W = {"header": 0.5, "header_name": 0.4, "cookie": 0.45, "server": 0.5, "body": 0.4, "status": 0.1}

